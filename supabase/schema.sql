create table if not exists public.products (
  id bigint generated by default as identity primary key,
  nome text not null,
  marca text,
  valor real not null default 0,
  genero text not null default 'Unissex',
  tamanhos text[] not null default '{}',
  cores text[] not null default '{}',
  observacao text,
  imagens text[] not null default '{}',
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;

drop policy if exists "public_read_products" on public.products;
drop policy if exists "public_write_products" on public.products;

create policy "public_read_products"
on public.products
for select
using (true);

create policy "public_write_products"
on public.products
for all
using (true)
with check (true);

insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = excluded.public;

drop policy if exists "public_read_product_images" on storage.objects;
drop policy if exists "public_upload_product_images" on storage.objects;

create policy "public_read_product_images"
on storage.objects
for select
using (bucket_id = 'product-images');

create policy "public_upload_product_images"
on storage.objects
for insert
to anon, authenticated
with check (bucket_id = 'product-images');
